<#
.SYNOPSIS
    SedaiBasic2 benchmark suite - The Computer Language Benchmarks Game.

.DESCRIPTION
    Runs the ten CLBG programs across every runtime available on this machine and reports wall-clock
    times side by side.

    Measurement rules, all of them learned the hard way on this project:

      ONE CLOCK FOR EVERYONE. Wall-clock around the process, for every runtime. The internal timer sb
      can report excludes startup and compilation, which the Python and Lua processes cannot exclude,
      so comparing the two would not be a comparison at all. Neither instruction counts nor MIPS are
      reported: CLBG does not measure them, and they say nothing about a runtime that executes fewer,
      bigger instructions.

      THERMOMETER. A fixed native binary (nbody_fbc_o2.exe, built by the real fbc) is timed before and
      after the session. It says how fast this machine is RIGHT NOW. If the two readings disagree, the
      machine changed underneath the session and its numbers are not comparable with anything.

      COOLDOWN between runs, so run N+1 does not inherit run N's heat.

      BEST-OF-N, the minimum rather than the mean. The mean carries the noise of whatever else the OS
      decided to do during the run.

      OUTPUT VERIFIED EVERY TIME. A program that dies early looks wonderfully fast. Every run's output
      is compared against a reference; an arm whose output does not match is reported as DIFF and its
      time is not credited. "No reference available on this machine" is reported as NO REF - which is
      a different thing from a failed comparison, and must never be read as a pass.

    SedaiBasic2 runs under all four execution profiles: interpreter, AOT, JIT and AOT+JIT.

    Copyright (c) 2025 Maurizio Cammalleri
    Released under GNU GPL v3

.PARAMETER Quick
    Use the reduced N values (seconds per run) instead of the standard CLBG ones (minutes per run).

.PARAMETER Runs
    Runs per arm; the reported time is the best of them. Default 1.

.PARAMETER Cooldown
    Seconds to idle between runs. Default: 0 with -Quick, 20 otherwise.

.PARAMETER Only
    Run only the named benchmarks (comma-separated).

.PARAMETER Runtime
    Run only the named runtimes: sedai, python, lua.

.PARAMETER Profile
    Run only the named SedaiBasic2 profiles: interp, aot, jit, aotjit.

.PARAMETER NoThermometer
    Skip the thermometer readings.

.PARAMETER Output
    Custom results filename. Default: results\BENCHMARK_<date>-<seconds>.md

.EXAMPLE
    .\benchmark.ps1 -Quick
.EXAMPLE
    .\benchmark.ps1 -Runs 3 -Cooldown 30
.EXAMPLE
    .\benchmark.ps1 -Only n-body,spectral-norm -Runtime sedai
#>

