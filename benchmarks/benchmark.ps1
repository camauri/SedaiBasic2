if ($Profile.Count -gt 0) {
    $valid = $Script:Profiles | ForEach-Object { $_.Key }
    $norm  = $Profile | ForEach-Object { $_.ToLower() }
    $bad   = @($norm | Where-Object { $_ -notin $valid })
    if ($bad.Count -gt 0) { Write-Host "ERROR: unknown profile: $($bad -join ', '). Valid: $($valid -join ', ')" -ForegroundColor Red; exit 1 }
    $Script:ProfileFilter = $norm
}

# --- benchmark filter -------------------------------------------------------
$suite = $Script:Suite
if ($Only.Count -gt 0) {
    $valid = $Script:Suite | ForEach-Object { $_.Name }
    $bad   = @($Only | Where-Object { $_ -notin $valid })
    if ($bad.Count -gt 0) {
        Write-Host "ERROR: unknown benchmark: $($bad -join ', ')" -ForegroundColor Red
        Write-Host "Valid: $($valid -join ', ')" -ForegroundColor Yellow
        exit 1
    }
    $suite = $Script:Suite | Where-Object { $_.Name -in $Only }
}

# A quick verification pass does not need a cooldown; a real measurement session does.
$Script:ActualCooldown = if ($Cooldown -ge 0) { $Cooldown } elseif ($Quick) { 0 } else { 20 }

foreach ($d in @($TempDir, $ResultsDir)) {
    if (-not (Test-Path $d)) { New-Item -ItemType Directory -Path $d -Force | Out-Null }
}

if (-not (Test-Path $SbExe)) {
    Write-Host "  ERROR: sb.exe not found at $SbExe - build it first." -ForegroundColor Red
    exit 1
}

Resolve-Runtimes
$sys = Get-SystemInfo

Write-Line "CPU:    $($sys.CPU)  ($($sys.CPUCores)c / $($sys.CPUThreads)t)"
Write-Line "Size:   $(if ($Quick) { 'QUICK (reduced N)' } else { 'STANDARD (the CLBG values)' })"
Write-Line "Runs:   best of $Runs, cooldown $($Script:ActualCooldown)s"
Write-Line "Python: $(if ($Script:PythonExe) { $Script:PythonExe } else { '(not found - Python arms and references unavailable)' })"
Write-Line "Lua:    $(if ($Script:LuaExe) { $Script:LuaExe } else { '(not found - Lua arms and references unavailable)' })"
if (-not (Test-Path $TempDir)) { [void](New-Item -ItemType Directory -Path $TempDir -Force) }
Resolve-NativeLibs

if (-not $Quick -and -not $Yes) {
    Write-Host ""
    Write-Line "The standard CLBG sizes take minutes per run. Close other applications first." 'Yellow'
    Write-Line "Use -Quick for a fast verification pass." 'Yellow'
    Write-Host ""
    $r = Read-Host "  Press ENTER to continue, or 'q' to quit"
    if ($r -eq 'q') { Write-Line "cancelled" 'Yellow'; exit 0 }
