function Get-ArmOrder {
    $order = @()
    if ($Script:RunPython) { $order += 'python' }
    if ($Script:RunLua)    { $order += 'lua' }
    if ($Script:RunSedai)  {
        foreach ($p in $Script:Profiles) {
            if ($Script:ProfileFilter.Count -gt 0 -and $p.Key -notin $Script:ProfileFilter) { continue }
            $order += $p.Key
        }
    }
    return $order
}

function Get-ArmLabel {
    param([string]$Key)
    if ($Key -eq 'python') { return 'Python' }
    if ($Key -eq 'lua')    { return 'Lua' }
    $p = $Script:Profiles | Where-Object { $_.Key -eq $Key }
    if ($p) { return $p.Label }
    return $Key
}

function Get-BadArms {
    # The arms under test are the SedaiBasic2 ones; Python and Lua are yardsticks. A yardstick that
    # cannot run here, or that disagrees with the designated reference, is a fact about that runtime
    # on this machine. It is reported, but it does not fail the benchmark, which verifies sb.
    #
    # The standing example is Lua's mandelbrot, and the cause was pinned byte by byte (2026-08-01).
    # TWO Windows text-mode artifacts, neither of them fixable from the .lua:
    #   1. stdout is in TEXT mode, so every 0x0A of the binary PBM is written as 0x0D 0x0A - visible
    #      from the header (`P4\r\n1000 1000\r\n`) and first hit in the body at byte 15966;
    #   2. the CLBG implementation is the parallel one: the parent collects its children through
    #      io.popen and reads THOSE pipes in text mode too, where 0x1A is the DOS end-of-file. The
    #      body matches the reference exactly up to byte 44909 - which is precisely the first 0x1A
    #      in the data - and then loses the rest: 103 430 bytes of real content against 125 013,
    #      827 rows of 1000.
    # Undoing (1) is possible, undoing (2) is not: the bytes are gone. And the script cannot avoid
    # either - stdout's mode is fixed by the CRT at process start, and this Lua 5.4.2 build rejects
    # io.popen(cmd, "rb") ("invalid mode"). So the output is not comparable on this platform; the
    # TIME still is, which is why the table prints it with a marker instead of hiding it behind DIFF.
    param([hashtable]$Result)
    return @($Result.Arms.Keys | Where-Object {
        (-not $Result.Arms[$_].IsReference) -and ($Result.Arms[$_].Verdict -in @('DIFF','FAIL'))
    })
}

function Get-OddYardsticks {
    param([hashtable]$Result)
    return @($Result.Arms.Keys | Where-Object {
        $Result.Arms[$_].IsReference -and ($Result.Arms[$_].Verdict -eq 'DIFF')
    })
}

function Get-BenchStatus {
    param([hashtable]$Result)
    if ($null -eq $Result.Expected) { return 'NO REF' }
    if ((Get-BadArms $Result).Count -eq 0) { return 'MATCH' }
    return 'CHECK'
}

function Show-ResultsTable {
    param([array]$Results)

    $order = Get-ArmOrder
    Write-Host ""
    Write-Host ("  " + ("=" * 96)) -ForegroundColor Cyan
    Write-Host "  RESULTS - wall-clock milliseconds, best of $Runs" -ForegroundColor Yellow
    Write-Host ("  " + ("=" * 96)) -ForegroundColor Cyan

    $header = "  {0,-20}" -f 'benchmark'
    foreach ($k in $order) { $header += ("{0,11}" -f (Get-ArmLabel $k)) }
    $header += "   verify"
    Write-Host $header -ForegroundColor White
    Write-Host ("  " + ("-" * 96)) -ForegroundColor DarkGray

    foreach ($r in $Results) {
        if (-not $r) { continue }
        $row = "  {0,-20}" -f $r.Name
        foreach ($k in $order) {
            $arm = $r.Arms[$k]
            if (-not $arm)                   { $row += ("{0,11}" -f '-') }
            elseif ($arm.Verdict -eq 'N/A')  { $row += ("{0,11}" -f 'n/a') }
            elseif ($arm.Verdict -eq 'FAIL') { $row += ("{0,11}" -f 'FAIL') }
            # A YARDSTICK whose output the platform mangles still produced a valid TIME: print it
            # with a marker rather than hiding it behind DIFF, or the row loses the only reference
            # point it has (see Get-BadArms for the mandelbrot/Lua case, diagnosed byte by byte).
            # An arm UNDER TEST that disagrees is a different thing entirely and stays DIFF.
            elseif ($arm.Verdict -eq 'DIFF') {
                if ($arm.IsReference) { $row += ("{0,11}" -f ((Format-Ms $arm.Ms) + '*')) }
                else                  { $row += ("{0,11}" -f 'DIFF') }
            }
            else                             { $row += ("{0,11}" -f (Format-Ms $arm.Ms)) }
        }
        $status = Get-BenchStatus $r
        $row += "   $status"
        $color = switch ($status) { 'MATCH' { 'Green' } 'NO REF' { 'Yellow' } default { 'Red' } }
        Write-Host $row -ForegroundColor $color
    }
    Write-Host ""
    Write-Line "MATCH = every arm's output equals the reference   NO REF = nothing to compare against" 'DarkGray'
    Write-Line "CHECK = at least one arm disagreed or failed     n/a = that runtime cannot run it here" 'DarkGray'
    Write-Line "*     = yardstick timed, but its output is not comparable on this platform (see the report)" 'DarkGray'
}

function Write-Report {
    param([array]$Results, [hashtable]$Sys, [int]$ThermoStart, [int]$ThermoEnd, [string]$Path)

    $order = Get-ArmOrder
    $md = [Text.StringBuilder]::new()

    [void]$md.AppendLine("# SedaiBasic2 - Benchmark Results")
    [void]$md.AppendLine()
    [void]$md.AppendLine("Generated: $((Get-Date).ToString('yyyy-MM-dd HH:mm:ss'))")
    [void]$md.AppendLine()
    [void]$md.AppendLine("Programs from [The Computer Language Benchmarks Game](https://salsa.debian.org/benchmarksgame-team/benchmarksgame/).")
    [void]$md.AppendLine()

    [void]$md.AppendLine("## Method")
    [void]$md.AppendLine()
    [void]$md.AppendLine("- **Wall-clock around the process, for every runtime.** Startup and compilation are counted for all of them, so the numbers are comparable.")
    [void]$md.AppendLine("- **Best of $Runs run(s)** per arm - the minimum, not the mean.")
    [void]$md.AppendLine("- **Cooldown** of $($Script:ActualCooldown)s between runs.")
    [void]$md.AppendLine("- **Output verified on every run.** An arm whose output differs is reported as DIFF and its time is not credited.")
    [void]$md.AppendLine("- Neither instruction counts nor MIPS are reported: CLBG does not measure them.")
    [void]$md.AppendLine("- Size: $(if ($Quick) { 'QUICK (reduced N)' } else { 'STANDARD (the CLBG values)' }).")
    [void]$md.AppendLine()
    if ($ThermoStart -gt 0 -and $ThermoEnd -gt 0) {
        $drift = [Math]::Abs($ThermoEnd - $ThermoStart) * 100.0 / $ThermoStart
        [void]$md.AppendLine("**Thermometer** (``nbody_fbc_o2.exe``, best of 3): $ThermoStart ms at the start, $ThermoEnd ms at the end - drift $("{0:F1}" -f $drift)%.")
        if ($drift -gt 5.0) {
            [void]$md.AppendLine()
            [void]$md.AppendLine("> The machine changed speed during the session. These numbers are not comparable with other sessions.")
        }
        [void]$md.AppendLine()
    }

    [void]$md.AppendLine("## System")
    [void]$md.AppendLine()
    [void]$md.AppendLine("| Item | Value |")
    [void]$md.AppendLine("|------|-------|")
    [void]$md.AppendLine("| CPU | $($Sys.CPU) |")
    [void]$md.AppendLine("| Cores / threads | $($Sys.CPUCores) / $($Sys.CPUThreads) |")
    [void]$md.AppendLine("| RAM | $($Sys.RAM) |")
    [void]$md.AppendLine("| OS | $($Sys.OS) ($($Sys.Architecture)) |")
    if ($Script:PythonExe) { [void]$md.AppendLine("| Python | ``$($Script:PythonExe)`` |") }
    if ($Script:LuaExe)    { [void]$md.AppendLine("| Lua | ``$($Script:LuaExe)`` |") }
    [void]$md.AppendLine()

    [void]$md.AppendLine("## Times (ms)")
    [void]$md.AppendLine()
    $hdr = "| benchmark | size |"
    $sep = "|---|---|"
    foreach ($k in $order) { $hdr += " " + (Get-ArmLabel $k) + " |"; $sep += "---:|" }
    $hdr += " verify |"; $sep += "---|"
    [void]$md.AppendLine($hdr)
    [void]$md.AppendLine($sep)

    foreach ($r in $Results) {
        if (-not $r) { continue }
        $row = "| $($r.Name) | $($r.NLabel) |"
        foreach ($k in $order) {
            $arm = $r.Arms[$k]
            if (-not $arm)                   { $row += " - |" }
            elseif ($arm.Verdict -eq 'N/A')  { $row += " n/a |" }
            elseif ($arm.Verdict -eq 'FAIL') { $row += " FAIL |" }
            elseif ($arm.Verdict -eq 'DIFF') {
                if ($arm.IsReference) { $row += " " + ("{0:F0}" -f $arm.Ms) + "\* |" }   # timed, output not comparable
                else                  { $row += " DIFF |" }
            }
            else                             { $row += " " + ("{0:F0}" -f $arm.Ms) + " |" }
        }
        $row += " $(Get-BenchStatus $r) |"
        [void]$md.AppendLine($row)
    }
    [void]$md.AppendLine()

    # Ratio against CPython - the yardstick this project has always used.
    if ($Script:RunPython -and $Script:RunSedai) {
        $sbKeys = @($order | Where-Object { $_ -notin @('python','lua') })
        if ($sbKeys.Count -gt 0) {
            [void]$md.AppendLine("## Ratio vs CPython")
            [void]$md.AppendLine()
            [void]$md.AppendLine("Below 1.00 means faster than CPython.")
            [void]$md.AppendLine()
            $hdr = "| benchmark |"; $sep = "|---|"
            foreach ($k in $sbKeys) { $hdr += " " + (Get-ArmLabel $k) + " |"; $sep += "---:|" }
            [void]$md.AppendLine($hdr)
            [void]$md.AppendLine($sep)
            foreach ($r in $Results) {
                if (-not $r) { continue }
                $py = $r.Arms['python']
                if (-not $py -or $py.Ms -le 0) { continue }
                $row = "| $($r.Name) |"
                foreach ($k in $sbKeys) {
                    $arm = $r.Arms[$k]
                    if (-not $arm -or $arm.Ms -le 0) { $row += " - |" }
                    else { $row += " " + ("{0:F2}x" -f ($arm.Ms / $py.Ms)) + " |" }
                }
                [void]$md.AppendLine($row)
            }
            [void]$md.AppendLine()
        }
    }

    [void]$md.AppendLine("## Verification")
    [void]$md.AppendLine()
    [void]$md.AppendLine("| benchmark | reference | outcome |")
    [void]$md.AppendLine("|---|---|---|")
    foreach ($r in $Results) {
        if (-not $r) { continue }
        $ref = if ($r.Verify -eq 'oracle') { "pure-Python oracle (correctness only, never timed)" } else { $r.Verify }
        $na  = @($r.Arms.Keys | Where-Object { $r.Arms[$_].Verdict -eq 'N/A' })
        $odd = Get-OddYardsticks $r
        $out = switch (Get-BenchStatus $r) {
            'MATCH'  { "every sb profile matches" }
            'NO REF' { "**not verified** - no runnable reference on this machine" }
            default  { "**check** - " + ((Get-BadArms $r | ForEach-Object { "$_ = $($r.Arms[$_].Verdict)" }) -join ', ') }
        }
        if ($na.Count -gt 0)  { $out += "; not runnable here: $($na -join ', ')" }
        if ($odd.Count -gt 0) {
            $out += "; **$($odd -join ', ') timed but its output is not comparable here** (marked \* in the table)"
            if ($r.Name -eq 'mandelbrot') {
                $out += " - Lua writes the binary PBM through a TEXT-mode stdout (0x0A becomes 0x0D 0x0A) and the parallel implementation reads its io.popen children in text mode too, where 0x1A is the DOS end-of-file: the body matches byte for byte up to the first 0x1A and then loses the rest. Not fixable from the script"
            }
        }
        [void]$md.AppendLine("| $($r.Name) | $ref | $out |")
    }
    [void]$md.AppendLine()

    $md.ToString() | Set-Content $Path -Encoding UTF8
}

