    $norm  = $Runtime | ForEach-Object { $_.ToLower() }
    $bad   = @($norm | Where-Object { $_ -notin $valid })
    if ($bad.Count -gt 0) { Write-Host "ERROR: unknown runtime: $($bad -join ', '). Valid: $($valid -join ', ')" -ForegroundColor Red; exit 1 }
    $Script:RunSedai  = 'sedai'  -in $norm
    $Script:RunPython = 'python' -in $norm
    $Script:RunLua    = 'lua'    -in $norm
