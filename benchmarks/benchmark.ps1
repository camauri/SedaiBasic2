function Resolve-Runtimes {
    # The project ships its own Python and Lua under benchmarks\runtime. If they are not there, fall
    # back to whatever the config file names, then to whatever is on PATH. A runtime that cannot be
    # found is not an error: its column is simply reported as unavailable.
    if (Test-Path $ConfigFile) {
        try {
            $cfg = Get-Content $ConfigFile -Raw | ConvertFrom-Json
            if ($cfg.PythonPath -and $cfg.PythonPath -ne 'disabled' -and (Test-Path $cfg.PythonPath)) {
                $Script:PythonExe = $cfg.PythonPath
            }
            if ($cfg.LuaPath -and $cfg.LuaPath -ne 'disabled' -and (Test-Path $cfg.LuaPath)) {
                $Script:LuaExe = $cfg.LuaPath
            }
        } catch { }
    }
    if (-not (Test-Path $Script:PythonExe)) {
        $c = Get-Command python -ErrorAction SilentlyContinue
        $Script:PythonExe = if ($c) { $c.Source } else { $null }
    }
    if (-not (Test-Path $Script:LuaExe)) {
        $c = Get-Command lua54 -ErrorAction SilentlyContinue
        if (-not $c) { $c = Get-Command lua -ErrorAction SilentlyContinue }
        $Script:LuaExe = if ($c) { $c.Source } else { $null }
    }
}

function Resolve-NativeLibs {
    # Two of the Python references are thin ctypes wrappers over a C library - pidigits over GMP,
    # regex-redux over PCRE2 - and both resolve it with ctypes.util.find_library(), which on Windows
    # searches PATH for a file named EXACTLY "gmp.dll" / "pcre2-8.dll". The libraries are commonly
    # present under their MinGW names (libgmp-10.dll, libpcre2-8-0.dll), so find_library returns
    # None, CDLL(None) raises, and both benchmarks lost their yardstick to a naming convention.
    #
    # So: find them wherever they are, keep a copy under the SPELLING ctypes wants in the Python
    # runtime directory next to the other runtimes, and put that directory on PATH. Verified
    # self-sufficient - the copies load with nothing else of their origin on PATH.
    #
    # benchmarks\runtime\python is the durable home (the harness populates it on the first run and
    # finds it there afterwards, so a machine is provisioned once). Nothing reaches the repository:
    # .gitignore excludes *.dll and *.exe everywhere, which is why the Lua runtime beside it is not
    # tracked either - each machine provides its own binaries.
    #
    # ⚠️ Lua's two missing pieces are MODULES (bn, rex_pcre2), not these libraries. When they turn
    # up they go in benchmarks\runtime\lua: that directory is already first in Lua's package.cpath,
    # so no PATH work is needed there - only rex_pcre2.dll's own dependency on pcre2-8.dll, which
    # Windows resolves from the directory of the executable.
    #
    # Not found = the two columns stay n/a exactly as before. This only ever ADDS a yardstick.
    $stage = Join-Path $PSScriptRoot 'runtime\python'
    $wanted = @(
        @{ As = 'gmp.dll';      Names = @('gmp.dll', 'libgmp-10.dll') }
        @{ As = 'pcre2-8.dll';  Names = @('pcre2-8.dll', 'libpcre2-8-0.dll') }
    )
    $dirs = @(
        (Join-Path $env:ProgramFiles 'Git\mingw64\bin')
        'C:\msys64\mingw64\bin'
        'C:\msys64\ucrt64\bin'
    ) + ($env:PATH -split ';')
    $found = @()
    foreach ($w in $wanted) {
        $dst = Join-Path $stage $w.As
        if (Test-Path $dst) { $found += $w.As; continue }
        foreach ($d in $dirs) {
            if ([string]::IsNullOrWhiteSpace($d) -or -not (Test-Path $d)) { continue }
            $hit = $null
            foreach ($n in $w.Names) {
                $p = Join-Path $d $n
                if (Test-Path $p) { $hit = $p; break }
            }
            if ($hit) {
                if (-not (Test-Path $stage)) { [void](New-Item -ItemType Directory -Path $stage -Force) }
                Copy-Item $hit $dst -Force
                $found += $w.As
                break
            }
        }
    }
    if ($found.Count -gt 0) {
        $env:PATH = "$stage;$($env:PATH)"
        Write-Line ("native libs for the ctypes references: {0}" -f ($found -join ', ')) 'DarkGray'
    }
}

# ============================================================================
#  EXECUTION
# ============================================================================

function Invoke-Timed {
    # Runs one process, wall-clock timed, with stdout captured to a file. cmd /c is used rather than
    # PowerShell redirection because PowerShell's ">" re-encodes the stream and corrupts any output
    # that is not plain text - fasta and mandelbrot both produce bytes that do not survive it.
    param(
        [string]  $Exe,
        [string[]]$Arguments = @(),
        [string]  $StdinFile = $null,
        [string]  $OutFile
    )

    $errFile = "$OutFile.err"
    $line = "`"$Exe`""
    foreach ($a in $Arguments) { $line += " `"$a`"" }
    if ($StdinFile) { $line += " < `"$StdinFile`"" }
    $line += " > `"$OutFile`" 2> `"$errFile`""

    $sw = [Diagnostics.Stopwatch]::StartNew()
    cmd /c $line | Out-Null
    $sw.Stop()
    $code = $LASTEXITCODE

    $err = ""
    if (Test-Path $errFile) {
        $err = (Get-Content $errFile -Raw -ErrorAction SilentlyContinue)
        Remove-Item $errFile -Force -ErrorAction SilentlyContinue
    }

    return @{
        Ms       = $sw.Elapsed.TotalMilliseconds
        ExitCode = $code
        Stderr   = $err
        Ok       = ($code -eq 0)
    }
}

function Get-OutputSignature {
    # Compares outputs by content, not byte-for-byte: CRLF versus LF and a trailing newline are a
    # property of the host's print routine, not of the computation. Everything else must match.
    param([string]$Path)
    if (-not (Test-Path $Path)) { return $null }
    $bytes = [IO.File]::ReadAllBytes($Path)
    if ($bytes.Length -eq 0) { return $null }
    $text  = [Text.Encoding]::Latin1.GetString($bytes) -replace "`r`n", "`n"
    $text  = $text.TrimEnd(@("`n", "`r", " ", "`t"))
    $md5   = [Security.Cryptography.MD5]::Create()
    return [BitConverter]::ToString($md5.ComputeHash([Text.Encoding]::Latin1.GetBytes($text)))
}

function Start-Cooldown {
    param([int]$Seconds)
    if ($Seconds -le 0) { return }
    Write-Host ("      cooling down {0}s ..." -f $Seconds) -ForegroundColor DarkGray -NoNewline
    Start-Sleep -Seconds $Seconds
    Write-Host "`r                                        `r" -NoNewline
}

function Read-Thermometer {
    # Best-of-3 on a fixed native binary. This is the machine's speed right now, in milliseconds.
    if (-not (Test-Path $ThermoExe)) { return 0 }
    $best = [double]::MaxValue
    foreach ($i in 1..3) {
        $r = Invoke-Timed -Exe $ThermoExe -OutFile (Join-Path $TempDir "thermo.out")
        if ($r.Ms -lt $best) { $best = $r.Ms }
    }
    return [int]$best
}

# ============================================================================
#  FASTA INPUT GENERATION
# ============================================================================

function Get-FastaInput {
    # k-nucleotide, regex-redux and reverse-complement all read the output of fasta. Generate it once
    # per N with the reference implementation, so every runtime is fed exactly the same bytes.
    param([long]$N)

    $path = Join-Path $TempDir "fasta_$N.txt"
    if ((Test-Path $path) -and (Get-Item $path).Length -gt 0) { return $path }

    Write-Line "generating the FASTA input, N=$N ..." 'DarkGray'
    if ($Script:PythonExe) {
        $r = Invoke-Timed -Exe $Script:PythonExe -Arguments @((Join-Path $PyDir 'fasta.py'), "$N") -OutFile $path
        if ($r.Ok -and (Test-Path $path) -and (Get-Item $path).Length -gt 0) { return $path }
    }
    if ($Script:LuaExe) {
        $r = Invoke-Timed -Exe $Script:LuaExe -Arguments @((Join-Path $LuaDir 'fasta.lua'), "$N") -OutFile $path
        if ($r.Ok -and (Test-Path $path) -and (Get-Item $path).Length -gt 0) { return $path }
    }
    if (Test-Path $path) { Remove-Item $path -Force -ErrorAction SilentlyContinue }
    return $null
}

# ============================================================================
#  ONE BENCHMARK
# ============================================================================

function Invoke-Arm {
    # Runs one arm ($RunCount times) and keeps the best time. Every run's output is signed; a run that
    # fails, or whose output is not reproducible, is reported rather than averaged away.
    param(
        [string]  $Label,
        [string]  $Exe,
        [string[]]$Arguments,
        [string]  $StdinFile,
        [string]  $OutFile,
        [int]     $RunCount,
        [int]     $CooldownSeconds,
        [switch]  $IsReference
    )

    $best = [double]::MaxValue
    $sig  = $null
    $fail = $null

    foreach ($i in 1..$RunCount) {
        Start-Cooldown $CooldownSeconds
        Write-Host ("      {0,-11} {1}/{2} ... " -f $Label, $i, $RunCount) -NoNewline -ForegroundColor DarkGray
        $r = Invoke-Timed -Exe $Exe -Arguments $Arguments -StdinFile $StdinFile -OutFile $OutFile
        if (-not $r.Ok) {
            $fail = if ($r.Stderr) { ($r.Stderr -split "`r?`n" | Where-Object { $_ } | Select-Object -First 1) }
                    else { "exit code $($r.ExitCode)" }
            Write-Host ("FAIL  ({0})" -f $fail) -ForegroundColor Red
            break
        }
        $thisSig = Get-OutputSignature $OutFile
        if ($null -eq $thisSig) {
            $fail = "no output"
            Write-Host "FAIL  (no output)" -ForegroundColor Red
            break
        }
        if ($null -eq $sig) { $sig = $thisSig }
        elseif ($sig -ne $thisSig) {
            $fail = "output not reproducible across runs"
            Write-Host "FAIL  (output changed between runs)" -ForegroundColor Red
            break
        }
        if ($r.Ms -lt $best) { $best = $r.Ms }
        Write-Host ("{0} ms" -f (Format-Ms $r.Ms)) -ForegroundColor DarkGray
    }

    # A COMPARISON runtime that cannot run the program here is not a benchmark failure: several CLBG
    # programs bind native libraries (GMP, PCRE2, lrexlib) that a stock Windows box does not have.
    # That is reported as unavailable, and does not count against the benchmark. Only SedaiBasic2 -
    # the thing under test - turns a failure into FAIL.
    if ($fail) { return @{ Ms = 0.0; Signature = $null; Error = $fail; IsReference = [bool]$IsReference } }
    return @{ Ms = $best; Signature = $sig; Error = $null; IsReference = [bool]$IsReference }
}

function Invoke-Benchmark {
    param([hashtable]$Bench, [int]$RunCount, [int]$CooldownSeconds)

    $name = $Bench.Name
    Write-Host ""
    Write-Host "  $name" -ForegroundColor Cyan -NoNewline
    Write-Host ("  - {0}" -f $Bench.Desc) -ForegroundColor DarkGray

    # Resolve N (or the FASTA input) for this run.
    $stdinFile = $null
    $sizeArgs  = @()
    if ($Bench.ContainsKey('StdinN')) {
        $fastaN = if ($Quick) { $Bench.StdinQuickN } else { $Bench.StdinN }
        $stdinFile = Get-FastaInput $fastaN
        if (-not $stdinFile) {
            Write-Line "cannot generate the FASTA input - skipping" 'Red'
            return $null
        }
        $nLabel = "stdin = fasta($fastaN)"
    } else {
        $n = if ($Quick) { $Bench.QuickN } else { $Bench.StdN }
        $sizeArgs = @("$n")
        $nLabel = "N = $n"
    }
    Write-Line $nLabel 'DarkGray'

    $result = @{
        Name   = $name
        NLabel = $nLabel
        Desc   = $Bench.Desc
        Verify = $Bench.Verify
        Arms   = @{}
    }

    # --- reference runtimes -------------------------------------------------
    if ($Script:RunPython -and $Script:PythonExe -and $Bench.Py) {
        $result.Arms['python'] = Invoke-Arm -Label 'python' -Exe $Script:PythonExe `
            -Arguments (@((Join-Path $PyDir $Bench.Py)) + $sizeArgs) -StdinFile $stdinFile `
            -OutFile (Join-Path $TempDir "$name.python.out") -RunCount $RunCount -CooldownSeconds $CooldownSeconds -IsReference
    }
    if ($Script:RunLua -and $Script:LuaExe -and $Bench.Lua) {
        $result.Arms['lua'] = Invoke-Arm -Label 'lua' -Exe $Script:LuaExe `
            -Arguments (@((Join-Path $LuaDir $Bench.Lua)) + $sizeArgs) -StdinFile $stdinFile `
            -OutFile (Join-Path $TempDir "$name.lua.out") -RunCount $RunCount -CooldownSeconds $CooldownSeconds -IsReference
    }

    # --- the expected output ------------------------------------------------
    # Whichever source the benchmark names: reuse it if it already ran as an arm, otherwise run it
    # once, untimed. An oracle is ALWAYS run untimed - it is not the engine the benchmark specifies.
    $expected = $null
    switch ($Bench.Verify) {
        'python' {
            $a = $result.Arms['python']
            if ($a -and -not $a.Error) { $expected = $a.Signature }
            elseif (-not $a -and $Script:PythonExe) {
                $out = Join-Path $TempDir "$name.ref.out"
                $r = Invoke-Timed -Exe $Script:PythonExe -Arguments (@((Join-Path $PyDir $Bench.Py)) + $sizeArgs) -StdinFile $stdinFile -OutFile $out
                if ($r.Ok) { $expected = Get-OutputSignature $out }
            }
        }
        'lua' {
            $a = $result.Arms['lua']
            if ($a -and -not $a.Error) { $expected = $a.Signature }
            elseif (-not $a -and $Script:LuaExe) {
                $out = Join-Path $TempDir "$name.ref.out"
                $r = Invoke-Timed -Exe $Script:LuaExe -Arguments (@((Join-Path $LuaDir $Bench.Lua)) + $sizeArgs) -StdinFile $stdinFile -OutFile $out
                if ($r.Ok) { $expected = Get-OutputSignature $out }
            }
        }
        'oracle' {
            if ($Script:PythonExe -and $Bench.Oracle) {
                $out = Join-Path $TempDir "$name.oracle.out"
                $r = Invoke-Timed -Exe $Script:PythonExe `
                    -Arguments (@((Join-Path $OracleDir $Bench.Oracle)) + $sizeArgs) -StdinFile $stdinFile -OutFile $out
                if ($r.Ok) { $expected = Get-OutputSignature $out }
            }
        }
    }
    if ($null -eq $expected) {
        Write-Line "no runnable reference on this machine - output CANNOT be verified" 'Yellow'
    }
    $result.Expected = $expected

    # --- SedaiBasic2, four profiles ----------------------------------------
    if ($Script:RunSedai) {
        $src = Join-Path $BasDir $Bench.Bas
        foreach ($p in $Script:Profiles) {
            if ($Script:ProfileFilter.Count -gt 0 -and $p.Key -notin $Script:ProfileFilter) { continue }
            $result.Arms[$p.Key] = Invoke-Arm -Label $p.Label -Exe $SbExe `
                -Arguments (@($src) + $sizeArgs + $p.Flags) -StdinFile $stdinFile `
                -OutFile (Join-Path $TempDir "$name.$($p.Key).out") -RunCount $RunCount -CooldownSeconds $CooldownSeconds
        }
    }

    # --- verdicts -----------------------------------------------------------
    foreach ($k in @($result.Arms.Keys)) {
        $arm = $result.Arms[$k]
        if ($arm.Error -and $arm.IsReference) { $arm.Verdict = 'N/A' }
        elseif ($arm.Error)                   { $arm.Verdict = 'FAIL' }
        elseif ($null -eq $expected)          { $arm.Verdict = 'NO REF' }
        elseif ($arm.Signature -eq $expected) { $arm.Verdict = 'MATCH' }
        else                                  { $arm.Verdict = 'DIFF' }
    }

    $na = @($result.Arms.Keys | Where-Object { $result.Arms[$_].Verdict -eq 'N/A' })
    if ($na.Count -gt 0) {
        Write-Line ("not available here: {0}" -f ($na -join ', ')) 'DarkGray'
    }
    $odd = Get-OddYardsticks $result
    if ($odd.Count -gt 0) {
        Write-Line ("yardstick disagrees with the reference (not our output): {0}" -f ($odd -join ', ')) 'Yellow'
    }
    $bad = Get-BadArms $result
    if ($bad.Count -eq 0) {
        if ($null -eq $expected) { Write-Line "every arm ran; output UNVERIFIED (no reference)" 'Yellow' }
        else                     { Write-Line "output verified: every sb profile MATCHes the reference" 'Green' }
    } else {
        Write-Line ("not clean: {0}" -f (($bad | ForEach-Object { "$_ = $($result.Arms[$_].Verdict)" }) -join ', ')) 'Red'
    }

    return $result
}

