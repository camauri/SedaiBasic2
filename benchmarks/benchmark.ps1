    Write-Host ""
    Write-Line "reading the thermometer ..." 'DarkGray'
    $thermoEnd = Read-Thermometer
    $drift = [Math]::Abs($thermoEnd - $thermoStart) * 100.0 / $thermoStart
    $col = if ($drift -gt 5.0) { 'Red' } else { 'DarkGray' }
