function Format-Ms {
    param([double]$Ms)
    if ($Ms -le 0)     { return "-" }
    if ($Ms -lt 10000) { return ("{0:F0}" -f $Ms) }
    return ("{0:F1}s" -f ($Ms / 1000.0))
}

